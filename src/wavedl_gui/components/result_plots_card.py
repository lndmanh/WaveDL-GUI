"""
WaveDL GUI — Result Plots Card

Displays diagnostic plot images generated by ``wavedl.test --plot`` after
a successful training run. Uses a SegmentedWidget for tab navigation and
QPixmap rendering for the already-saved PNG images.
"""

from __future__ import annotations

import os

from PySide6.QtCore import Qt, QTimer, QUrl, Signal
from PySide6.QtGui import (
    QColor,
    QDesktopServices,
    QFont,
    QImageReader,
    QPainter,
    QPainterPath,
    QPixmap,
)
from PySide6.QtWidgets import QHBoxLayout, QLabel, QVBoxLayout, QWidget
from qfluentwidgets import (
    CaptionLabel,
    FluentIcon as FIF,
    IconWidget,
    IndeterminateProgressRing,
    SegmentedWidget,
    SimpleCardWidget,
    TransparentPushButton,
    isDarkTheme,
    setFont,
)

from ..common.theme_colors import muted_text_color as _muted_text_color


# ── Human-readable names for plot basenames ─────────────────────────────────

_PLOT_DISPLAY_NAMES: dict[str, str] = {
    "scatter_all": "Scatter Plot",
    "error_histogram": "Error Histogram",
    "residuals": "Residuals",
    "bland_altman": "Bland-Altman",
    "qq_plot": "Q-Q Plot",
    "error_correlation": "Correlation",
    "relative_error": "Relative Error",
    "error_cdf": "Error CDF",
    "prediction_vs_index": "Pred vs Index",
    "error_boxplot": "Error Box Plot",
}


def _display_name_for(path: str) -> str:
    """Derive a human-readable tab name from a plot file path."""
    base = os.path.splitext(os.path.basename(path))[0]
    return _PLOT_DISPLAY_NAMES.get(base, base.replace("_", " ").title())


# ── Scalable image label ─────────────────────────────────────────────────────


class _ScaledImageLabel(QLabel):
    """QLabel that scales a QPixmap to fit while preserving aspect ratio."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self._original_pixmap: QPixmap | None = None
        self.setAlignment(Qt.AlignCenter)
        self.setMinimumHeight(420)

    def setPixmap(self, pixmap: QPixmap):
        self._original_pixmap = pixmap
        self._rescale()

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self._rescale()

    def _rescale(self):
        if self._original_pixmap is None or self._original_pixmap.isNull():
            return
        scaled = self._original_pixmap.scaled(
            self.size(),
            Qt.KeepAspectRatio,
            Qt.SmoothTransformation,
        )
        super().setPixmap(scaled)


# ── Result Plots Card ────────────────────────────────────────────────────────


class ResultPlotsCard(SimpleCardWidget):
    """Tabbed gallery of diagnostic plots generated after training.

    Each tab displays a single plot image loaded from disk. The card shows
    a loading spinner while plots are being generated and hides itself
    when there are no plots to display.
    """

    retryRequestedSig = Signal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self._image_paths: list[str] = []
        self._current_tab: str | None = None
        self._init_ui()
        self.hide()

    # ── UI ────────────────────────────────────────────────────────────

    def _init_ui(self):
        self.setBorderRadius(10)

        root = QVBoxLayout(self)
        root.setContentsMargins(0, 0, 0, 0)
        root.setSpacing(0)

        content = QVBoxLayout()
        content.setContentsMargins(24, 20, 24, 20)
        content.setSpacing(0)
        root.addLayout(content)

        # ── Header row ────────────────────────────────────────────
        header_row = QHBoxLayout()
        header_row.setSpacing(8)

        ic = IconWidget(FIF.PHOTO, self)
        ic.setFixedSize(16, 16)
        header_row.addWidget(ic)

        self._title_label = CaptionLabel("DIAGNOSTIC PLOTS", self)
        self._title_label.setTextColor(_muted_text_color(), _muted_text_color())
        setFont(self._title_label, 10, QFont.Weight.Bold)
        header_row.addWidget(self._title_label)
        header_row.addStretch()

        self.retryButton = TransparentPushButton(
            FIF.SYNC, self.tr("Retry Plot Delivery"), self
        )
        self.retryButton.clicked.connect(self.retryRequestedSig.emit)
        self.retryButton.hide()
        header_row.addWidget(self.retryButton)

        self._openFolderBtn = TransparentPushButton(
            FIF.FOLDER, self.tr("Open Folder"), self
        )
        self._openFolderBtn.clicked.connect(self._open_output_folder)
        self._openFolderBtn.hide()
        header_row.addWidget(self._openFolderBtn)

        content.addLayout(header_row)
        content.addSpacing(12)

        # ── Tab bar ────────────────────────────────────────────────
        self._pivot = SegmentedWidget(self)
        self._pivot.hide()
        content.addWidget(self._pivot)
        content.addSpacing(8)

        # ── Image container ────────────────────────────────────────
        self._image_container = QVBoxLayout()
        self._image_container.setContentsMargins(0, 0, 0, 0)
        self._image_container.setSpacing(0)
        content.addLayout(self._image_container)

        # ── Spinner (shown while generating) ───────────────────────
        self._spinner_widget = QWidget(self)
        spinner_layout = QVBoxLayout(self._spinner_widget)
        spinner_layout.setAlignment(Qt.AlignCenter)

        self._spinner = IndeterminateProgressRing(self._spinner_widget)
        self._spinner.setFixedSize(36, 36)
        spinner_layout.addWidget(self._spinner, 0, Qt.AlignCenter)

        self._spinner_caption = CaptionLabel(
            "Generating diagnostic plots…", self._spinner_widget
        )
        self._spinner_caption.setTextColor(_muted_text_color(), _muted_text_color())
        setFont(self._spinner_caption, 11)
        spinner_layout.addWidget(self._spinner_caption, 0, Qt.AlignCenter)

        self._spinner_widget.setMinimumHeight(420)
        self._spinner_widget.hide()
        self._image_container.addWidget(self._spinner_widget)

        # ── Image label (current plot) ─────────────────────────────
        self._image_label = _ScaledImageLabel(self)
        self._image_label.hide()
        self._image_container.addWidget(self._image_label, 1)

    # ── Layout helpers ────────────────────────────────────────────────

    def _showCard(self):
        self.setMinimumHeight(560)
        self.show()
        QTimer.singleShot(0, self, self._updateParentLayout)

    def _updateParentLayout(self):
        parent = self.parentWidget()
        if parent is not None:
            parent.adjustSize()
            parent.updateGeometry()

    # ── Public API ────────────────────────────────────────────────────

    def setGenerating(self):
        """Show the loading spinner while plots are being generated."""
        self._image_paths = []
        self._current_tab = None
        self._image_label.hide()
        self._pivot.hide()
        self._openFolderBtn.hide()
        self.retryButton.hide()
        self._spinner.show()
        self._spinner_caption.setText(self.tr("Generating diagnostic plots…"))
        self._spinner_widget.show()
        self._showCard()

    def setReconnectRequired(self, retry_available=True):
        """Stop the spinner and offer identity-preserving delivery retry."""
        self._spinner.hide()
        self._spinner_caption.setText(
            self.tr("Plot connection or delivery is uncertain. Retry to reconnect.")
        )
        self._spinner_widget.show()
        self.retryButton.setEnabled(retry_available)
        self.retryButton.show()
        self._showCard()

    def setPlotPaths(self, paths: list[str]):
        """Populate the gallery with the given plot image paths."""
        self._spinner_widget.hide()
        self.retryButton.hide()

        if not paths:
            self.hide()
            return

        self._image_paths = paths

        # Rebuild tabs
        self._pivot.clear()
        for path in paths:
            name = _display_name_for(path)
            self._pivot.addItem(
                routeKey=path,
                text=name,
                onClick=lambda checked=False, p=path: self._show_image(p),
            )

        self._pivot.show()
        self._openFolderBtn.show()

        # Show first image
        self._pivot.setCurrentItem(paths[0])
        self._show_image(paths[0])
        self._showCard()

    def reset(self):
        """Reset to initial hidden state."""
        self._image_paths = []
        self._current_tab = None
        self._image_label.hide()
        self._pivot.hide()
        self._openFolderBtn.hide()
        self._spinner_widget.hide()
        self.retryButton.hide()
        self.setMinimumHeight(0)
        self.setFixedHeight(0)
        self.hide()
        QTimer.singleShot(0, self, self._updateParentLayout)

    # ── Internal ──────────────────────────────────────────────────────

    def _show_image(self, path: str):
        """Load and display a single plot image."""
        if path == self._current_tab:
            return

        if not os.path.isfile(path):
            return

        # Published bytes still cross a trust boundary. A .png name must never
        # select Qt's SVG/HTML-capable content-sniffing plugins or a huge bitmap.
        reader = QImageReader(path, b"png")
        reader.setAutoDetectImageFormat(False)
        reader.setDecideFormatFromContent(False)
        size = reader.size()
        if (
            not reader.canRead()
            or size.width() < 1
            or size.height() < 1
            or size.width() > 8192
            or size.height() > 8192
            or size.width() * size.height() > 16_777_216
        ):
            self._image_label.clear()
            self._image_label.setText(
                self.tr("This plot is not a supported, bounded PNG image.")
            )
            self._image_label.show()
            return
        pixmap = QPixmap.fromImage(reader.read())
        if pixmap.isNull():
            return

        self._image_label.setPixmap(pixmap)
        self._image_label.show()
        self._current_tab = path

    def _open_output_folder(self):
        """Open the folder containing the plot images."""
        if not self._image_paths:
            return
        folder = os.path.dirname(self._image_paths[0])
        if not os.path.isdir(folder):
            return
        QDesktopServices.openUrl(QUrl.fromLocalFile(folder))

    # ── Custom painting (accent bar matching other cards) ─────────────

    def _normalBackgroundColor(self):
        return QColor(255, 255, 255, 13 if isDarkTheme() else 170)

    def paintEvent(self, e):
        p = QPainter(self)
        p.setRenderHint(QPainter.Antialiasing)
        r = self.borderRadius

        # Card background
        p.setBrush(self._normalBackgroundColor())
        p.setPen(Qt.NoPen)
        p.drawRoundedRect(self.rect().adjusted(1, 1, -1, -1), r, r)

        # Top accent bar (green = success)
        accent_color = QColor("#16a34a") if not isDarkTheme() else QColor("#4ade80")
        accent_rect = self.rect().adjusted(1, 1, -1, 0)
        accent_rect.setHeight(4)
        path = QPainterPath()
        path.addRoundedRect(
            accent_rect.x(),
            accent_rect.y(),
            accent_rect.width(),
            r * 2,
            r,
            r,
        )
        clip_rect = QPainterPath()
        clip_rect.addRect(
            accent_rect.x(),
            accent_rect.y(),
            accent_rect.width(),
            accent_rect.height(),
        )
        path = path.intersected(clip_rect)
        p.setBrush(accent_color)
        p.drawPath(path)

        p.end()
